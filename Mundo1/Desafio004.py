algo = input ("digite algo:")
print("o tipo primitivo desse valor e",type(algo))
print(" um numero:",algo.isnumeric())
print("uma letra:",algo.isalpha())
print("e uma letra ou numero:",algo.isalnum())
print("e so espaco",algo.isspace())
print("esta tudo em maiusculas",algo.isupper())
print("esta tudo em minusculos",algo.islower())
print("e capitalizado",algo.istitle())